#!/bin/sh
# platform: host-agnostic -- builds the staged static archive and dylib's x86_64 programs; runs them on 10.9 (RECAULK_TEST_PHASE)
# spec: README.md "Floating point" -- fma, fmal and truncl from a program that links librecaulk.a and one
#       relinked onto libRecaulkSystem.dylib, against tests/c/libm_cases.h; fmaf, trunc and truncf stay
#       the system's, and the same cases hold them to the same results.
set -eu
cd "$(dirname "$0")/.."
. tests/helpers/built.sh
cc() { "$CC" $FLAGS -arch x86_64 -Wall -Wextra -Werror -fno-builtin "$@"; }
if compiling; then
  py="$(command -v python3 || command -v python)" || { echo "FAIL: no python3 or python to regenerate tests/c/libm_cases.h"; exit 1; }
  count="$(sed -n '1s|^/\* Generated by tests/c/gen_libm_cases.py \([0-9]*\):.*|\1|p' tests/c/libm_cases.h)"
  [ -n "$count" ] || { echo "FAIL: tests/c/libm_cases.h does not say how gen_libm_cases.py made it"; exit 1; }
  "$py" tests/c/gen_libm_cases.py "$count" | cmp -s - tests/c/libm_cases.h \
    || { echo "FAIL: tests/c/libm_cases.h is not what tests/c/gen_libm_cases.py $count prints; regenerate it"; exit 1; }
  cc tests/c/libm_fixes.c "$T/lib/librecaulk.a" -o "$(tbin static)"
  cc tests/c/libm_fixes.c -L"$T/lib" -lRecaulkSystem -o "$(tbin dylib)"
  check_loads "$(tbin static)" "$(tbin dylib)"
  for s in _fma _fmal _truncl; do
    "$NM" -u "$(tbin static)" | grep -qxF "$s" \
      && { echo "FAIL: the librecaulk.a program imports $s from libSystem instead of carrying Recaulk's"; exit 1; }
    "$NM" -m "$(tbin dylib)" | grep -qF "(undefined) external $s (from libRecaulkSystem)" \
      || { echo "FAIL: the libRecaulkSystem.dylib program does not take $s from the dylib"; exit 1; }
  done
  for s in _fmaf _trunc _truncf; do
    "$NM" -u "$(tbin static)" | grep -qxF "$s" \
      || { echo "FAIL: the librecaulk.a program does not import $s from libSystem; 10.9's is right"; exit 1; }
  done
fi
runtime_half
fail=0
"$(tbin static)" || { echo "FAIL: the librecaulk.a program exited $?"; fail=1; }
# platform: SIP strips DYLD_* from protected binaries such as /bin/sh, so it is set where the program is exec'd
DYLD_LIBRARY_PATH="$T/lib" "$(tbin dylib)" || { echo "FAIL: the libRecaulkSystem.dylib program exited $?"; fail=1; }
[ "$fail" = 0 ] && echo "libm-fixes OK"
exit $fail
